@pytest.mark.asyncio
async def test_error_in_market_data_does_not_break_batch():
    sig_a = _signal(signal_id="sig_a", ticker="AAPL")
    sig_b = _signal(signal_id="sig_b", ticker="MSFT")
    rw_b = ReturnWindow(
        window="24h", return_pct=-0.012, pre_price=400.0, post_price=395.2, volatility=0.01,
    )

    async def fake_market(ticker, **kwargs):
        if ticker == "AAPL":
            raise RuntimeError("Alpha Vantage 429")
        return [rw_b]

    with patch(
        "src.ingestion.feedback_loop.list_unlabeled_expired",
        return_value=[sig_a, sig_b],
    ), patch(
        "src.ingestion.feedback_loop.compute_post_event_returns",
        side_effect=fake_market,
    ), patch(
        "src.ingestion.feedback_loop.update_actual_move",
        return_value=True,
    ) as mock_update:
        stats = await label_expired_signals()

    assert stats["scanned"] == 2
    assert stats["labeled"] == 1
    assert stats["errors"] == 1
    mock_update.assert_called_once_with("sig_b", -0.012)


@pytest.mark.asyncio
async def test_passes_signal_specific_window_to_market_data():
    sig = _signal(impact_window="1w")
    rw = ReturnWindow(
        window="1w", return_pct=0.05, pre_price=100.0, post_price=105.0, volatility=0.02,
    )
    captured: dict = {}

    async def fake_market(ticker, event_timestamp, windows=None):
        captured["windows"] = windows
        return [rw]

    with patch(
        "src.ingestion.feedback_loop.list_unlabeled_expired",
        return_value=[sig],
    ), patch(
        "src.ingestion.feedback_loop.compute_post_event_returns",
        side_effect=fake_market,
    ), patch(
        "src.ingestion.feedback_loop.update_actual_move",
        return_value=True,
    ):
        await label_expired_signals()

    assert captured["windows"] == ["1w"]
